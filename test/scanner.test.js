'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const scanner = require('../src/scanner');
test('recursive scan, case-insensitive covers, stable IDs and missing directories', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'kratos-test-'));
  t.after(() => fs.rm(root, { recursive:true, force:true }));
  await fs.mkdir(path.join(root,'nested'));
  for (const file of ['BanjoKazooie [USA].ISO','BanjoKazooie [USA].PNG','ignored.txt','nested/Viva_Pinata.god','nested/default.xex']) await fs.writeFile(path.join(root,file),'');
  const games = await scanner.scanDirectory(root);
  assert.equal(games.length,3);
  assert.equal(games[0].title,'Banjo Kazooie');
  assert.equal(games[0].uses_fallback_art,false);
  assert.equal(games.find(g=>g.title==='Viva Pinata').uses_fallback_art,true);
  assert.deepEqual(await scanner.scanDirectory(root),games);
  await assert.rejects(scanner.scanDirectory(path.join(root,'missing')));
});
test('ROM folder scans ignore executables; explicitly selected executables get adjacent covers without Xbox metadata', async t => {
  const root=await fs.mkdtemp(path.join(os.tmpdir(),'kratos-exe-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  await fs.writeFile(path.join(root,'Lost Odyssey Recomp.exe'),'not an Xbox package');
  await fs.writeFile(path.join(root,'lost odyssey recomp.PNG'),'cover');
  assert.deepEqual(await scanner.scanDirectory(root),[],'unselected executables are not discovered in ROM folders');
  const [game]=await scanner.scanExecutables([path.join(root,'Lost Odyssey Recomp.exe')]);
  assert.equal(game.title,'Lost Odyssey Recomp');
  assert.equal(game.cover_art_path,path.join(root,'lost odyssey recomp.PNG'));
  assert.equal(game.uses_fallback_art,false);
  assert.equal(game.title_id,undefined);
  assert.deepEqual(await scanner.scanExecutables([path.join(root,'Lost Odyssey Recomp.exe')]),[game]);
  await assert.rejects(scanner.scanExecutables([path.join(root,'lost odyssey recomp.PNG')]),/Invalid executable game path/);
});
test('extensionless STFS packages are games and carry title metadata', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'kratos-test-'));
  t.after(() => fs.rm(root, { recursive:true, force:true }));
  const header = Buffer.alloc(0x500);
  header.write('LIVE', 0, 'latin1'); header.writeUInt32BE(0x58410954, 0x360); header.writeUInt32BE(0x69C685B7, 0x354);
  Buffer.from('Banjo-Kazooie', 'utf16le').swap16().copy(header, 0x411);
  const god = Buffer.from(header); Buffer.alloc(0x80).copy(god, 0x411); Buffer.from('Viva Pinata', 'utf16le').swap16().copy(god, 0x411);
  await fs.mkdir(path.join(root, '4D5305E5', '00007000'), { recursive: true });
  await fs.writeFile(path.join(root, 'Banjo-Kazooie (World) (XBLA)'), header);
  await fs.writeFile(path.join(root, '4D5305E5', '00007000', '0123456789ABCDEF0123456789ABCDEF01234567'), god);
  await fs.writeFile(path.join(root, 'README'), 'not a package');
  await fs.writeFile(path.join(root, 'Broken.iso'), 'not a disc');
  const games = await scanner.scanDirectory(root);
  assert.deepEqual(games.map(g => [g.title, g.title_id || null]), [['Banjo Kazooie', '58410954'], ['Broken', null], ['Viva Pinata', '58410954']]);
  assert.equal(games[0].media_id, '69C685B7');
});
test('library persistence, legacy PIN migration, authentication and corrupt files', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(),'kratos-test-'));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const file = path.join(root,'library.json');
  const library = await scanner.loadLibrary(file);
  assert.equal(scanner.verifyPin('1234',library.admin_credential),true);
  assert.equal(library.admin_pin_required,false,'a new install starts with no PIN: it is opt-in');
  assert.equal(library.pin_is_default,true,'and its PIN is a placeholder until the owner sets one');
  assert.equal(scanner.verifyPin('9999',library.admin_credential),false);
  assert.equal(scanner.verifyPin(null,library.admin_credential),false);
  await scanner.saveLibrary(file,{platform_os:'win32',rom_directory:'',xenia_executable:'',admin_pin:'8765',games:[]});
  const migrated=await scanner.loadLibrary(file);
  assert.equal(scanner.verifyPin('8765',migrated.admin_credential),true);
  assert.equal('admin_pin' in JSON.parse(await fs.readFile(file,'utf8')),false);
  await fs.writeFile(file,'broken');
  await assert.rejects(scanner.loadLibrary(file),/Cannot read library/);
});
test('several ROM folders: one list, no duplicates, an unreadable folder is reported and does not hide the rest', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'kratos-multi-'));
  t.after(() => fs.rm(root, { recursive:true, force:true }));
  const [a, b] = [path.join(root,'a'), path.join(root,'b')];
  await fs.mkdir(path.join(a,'sub'), { recursive:true }); await fs.mkdir(b);
  await fs.writeFile(path.join(a,'Halo.iso'),''); await fs.writeFile(path.join(a,'sub','Fable.iso'),''); await fs.writeFile(path.join(b,'Gears.iso'),'');
  const failed = [];
  const games = await scanner.scanDirectories([a, b, a, path.join(root,'unplugged'), path.join(a,'sub')], undefined, folder => failed.push(folder));
  assert.deepEqual(games.map(game => game.title), ['Fable','Gears','Halo']);
  assert.deepEqual(failed, [path.join(root,'unplugged')]);
  await assert.rejects(scanner.scanDirectories([path.join(root,'unplugged')]), 'without a reporter the error still surfaces');
  assert.deepEqual(scanner.romFolders({ rom_directory: a }), [a], 'a library from before several folders');
  assert.deepEqual(scanner.romFolders({ rom_directory: a, rom_directories: [b, b, '', 7] }), [b]);
  assert.deepEqual(scanner.romFolders({ rom_directory: '' }), []);
});
